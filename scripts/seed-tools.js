async function fetchExistingRecords() {
  const map = new Map(); // slug → recordId
  let offset = '';

  do {
    const params = new URLSearchParams({ 'fields[]': 'slug' });
    if (offset) params.set('offset', offset);

    const res = await fetch(`https://api.airtable.com/v0/${BASE_ID}/${TABLE_ID}?${params}`, {
      headers: { Authorization: `Bearer ${API_KEY}` },
    });

    if (!res.ok) {
      const err = await res.text();
      throw new Error(`Airtable API error ${res.status}: ${err}`);
    }

    const data = await res.json();
    for (const record of data.records) {
      if (record.fields.slug) map.set(record.fields.slug, record.id);
    }
    offset = data.offset ?? '';
  } while (offset);

  return map;
}

